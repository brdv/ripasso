/** The column label under a model verb: its group, or its auxiliary in the passato prossimo. */
export function modelLabel(model: ModelVerb, tense: Tense): string {
  if (tense === "passato_prossimo") return `met ${model.auxiliary ?? "avere"}`;
  return `-${conjugationClass(model.lemma)}${model.isc ? " met -isc-" : ""}`;
}

export interface IrregularRow {
  lemma: string;
  /** The irregular piece itself (participle or stem), for a list. */
  piece?: string;
  /** Forms per person for a grid, or the io form as an example for a list. */
  forms: FormSegment[][];
}

/** The rows of a tense's irregular section, generated by the conjugation rules. */
export function irregularRows(section: IrregularGrid | IrregularList, tense: Tense): IrregularRow[] {
  if (section.shape === "grid") {
    return section.verbs.map((lemma) => ({
      lemma,
      forms: PERSONS.map((person) => conjugate(lemma, tense, person, { irregular: IRREGULAR_VERBS[lemma] }) ?? []),
    }));
  }
  return Object.entries(IRREGULAR_VERBS).flatMap(([lemma, irregular]): IrregularRow[] => {
    if (section.kind === "participle") {
      // The participle alone: the example would need the verb's auxiliary.
      return irregular.participle ? [{ lemma, piece: irregular.participle, forms: [] }] : [];
    }
    if (!irregular.futureStem) return [];
    return [{ lemma, piece: `${irregular.futureStem}-`, forms: [conjugate(lemma, tense, "io", { irregular }) ?? []] }];
  });
}
