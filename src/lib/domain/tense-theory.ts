export interface IrregularExample {
  lemma: string;
  /** The forms to show, each marked when it is one of the verb's irregularities. */
  forms: Array<{ text: string; irregular: boolean }>;
}

/** The base verbs that leave the rules for `kind`, with the forms that show how. */
export function irregularExamples(kind: IrregularKind): IrregularExample[] {
  return Object.entries(IRREGULAR_VERBS).flatMap(([lemma, irregular]): IrregularExample[] => {
    if (kind === "participle") {
      return irregular.participle ? [{ lemma, forms: [{ text: irregular.participle, irregular: true }] }] : [];
    }
    if (kind === "futureStem") {
      return irregular.futureStem ? [{ lemma, forms: [{ text: `${irregular.futureStem}-`, irregular: true }] }] : [];
    }
    const overrides = irregular.forms?.[kind] ?? {};
    if (Object.keys(overrides).length === 0 && !(kind === "imperfetto" && irregular.imperfettoStem)) return [];
    return [
      {
        lemma,
        forms: PERSONS.map((person) => ({
          text: formText(conjugate(lemma, kind, person, { irregular }) ?? []),
          irregular: person in overrides || kind === "imperfetto",
        })),
      },
    ];
  });
}
